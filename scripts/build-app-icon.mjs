#!/usr/bin/env node
/**
 * Generate the Fann app icon set.
 *
 *   node scripts/build-app-icon.mjs
 *
 * Option D from the rebrand plan: a mango tile, a 2px-equivalent ink
 * keyline, and the ink dachshund. The keyline is not decoration — mango
 * separates from nothing light, so without it the tile dissolves into a
 * light browser chrome. Measured edge separation:
 *
 *   tile vs light chrome #DEE1E6   13.50
 *   tile vs dark chrome  #35363A    6.17
 *
 * Every measurement here is a PROPORTION of the icon width, so 16px and
 * 512px render the same picture. Do not hardcode a pixel keyline: 2px
 * disappears at 16 and overwhelms at 512.
 *
 * Re-run after changing public/brand/fann-dog.svg.
 */

import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync, unlinkSync, existsSync } from "node:fs";

const MANGO = "#FFA62B";
const INK = "#1E1712";

const RADIUS = 0.225; // corner radius, fraction of width
const KEYLINE = 0.055; // inset stroke weight, fraction of width
const DOG_INSET = 0.08; // standard icons: inset each side

/**
 * Maskable icons: how much of the frame the dog spans.
 *
 * The plan said 80%. It is 72%, and this is the one number in the plan that
 * measurement contradicted rather than confirmed.
 *
 * Android guarantees only the centred circle of 80% DIAMETER; anything
 * outside it may be masked away. The dog is a ~2:1 silhouette, so its
 * extremes sit far out along the horizontal axis. Rendered and measured, its
 * furthest ink is at 0.5351x its own width from centre — so at 80% of the
 * frame the ink reaches 0.4281 of the icon, against a safe limit of 0.4000,
 * and the nose and tail are exactly what a circular mask would cut. The
 * largest width that actually fits is 74.7%.
 *
 * 72% leaves real margin for antialiasing and rounding. If the artwork is
 * ever retraced, re-derive it: render the dog alone on a square canvas at
 * width W, find the furthest opaque pixel from centre (call it R), and the
 * largest safe span is 0.4 / (R/W). For this trace that is 0.747.
 */
const DOG_MASKABLE = 0.72;

const dogSvg = readFileSync("public/brand/fann-dog.svg", "utf8");
const DOG_VIEWBOX = "0 0 948 482";
const DOG_ASPECT = 948 / 482;
const dogPath = dogSvg.match(/<path d="([^"]+)"/)[1];

/** One icon as an SVG string. `dogSpan` is the dog's width as a fraction of S. */
function iconSvg(S, { dogSpan = 1 - 2 * DOG_INSET, keyline = true } = {}) {
  const k = S * KEYLINE;
  const r = S * RADIUS;
  const dw = S * dogSpan;
  const dh = dw / DOG_ASPECT;
  const dx = (S - dw) / 2;
  const dy = (S - dh) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">
  <rect width="${S}" height="${S}" rx="${r}" fill="${MANGO}"/>
  ${
    keyline
      ? `<rect x="${k / 2}" y="${k / 2}" width="${S - k}" height="${S - k}" rx="${Math.max(0, r - k / 2)}"
        fill="none" stroke="${INK}" stroke-width="${k}"/>`
      : ""
  }
  <svg x="${dx}" y="${dy}" width="${dw}" height="${dh}" viewBox="${DOG_VIEWBOX}"
       fill="${INK}" fill-rule="evenodd"><path d="${dogPath}"/></svg>
</svg>`;
}

async function png(S, opts, out, { flatten = false } = {}) {
  let img = sharp(Buffer.from(iconSvg(S, opts))).resize(S, S);
  // Apple refuses transparency on the touch icon; the tile is opaque anyway,
  // but flattening guarantees no alpha channel survives the round trip.
  if (flatten) img = img.flatten({ background: MANGO });
  await img.png().toFile(out);
  return out;
}

/** A multi-resolution .ico whose entries are PNGs (every modern browser, Vista+). */
async function ico(sizes, out) {
  const blobs = await Promise.all(
    sizes.map((S) => sharp(Buffer.from(iconSvg(S))).resize(S, S).png().toBuffer()),
  );
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(sizes.length, 4);

  let offset = 6 + 16 * sizes.length;
  const entries = sizes.map((S, i) => {
    const e = Buffer.alloc(16);
    e.writeUInt8(S >= 256 ? 0 : S, 0); // width  (0 means 256)
    e.writeUInt8(S >= 256 ? 0 : S, 1); // height
    e.writeUInt8(0, 2); // palette count
    e.writeUInt8(0, 3); // reserved
    e.writeUInt16LE(1, 4); // colour planes
    e.writeUInt16LE(32, 6); // bits per pixel
    e.writeUInt32LE(blobs[i].length, 8);
    e.writeUInt32LE(offset, 12);
    offset += blobs[i].length;
    return e;
  });
  writeFileSync(out, Buffer.concat([header, ...entries, ...blobs]));
  return out;
}

mkdirSync("public/icons", { recursive: true });

// The vector one keeps the same geometry rather than a hand-drawn copy.
writeFileSync(
  "public/icon.svg",
  `<!-- Generated by scripts/build-app-icon.mjs — do not edit. -->\n${iconSvg(512)}\n`,
  "utf8",
);

const written = ["public/icon.svg"];

/*
 * The favicon goes to src/app/, NOT public/.
 *
 * Next's App Router treats src/app/favicon.ico as a file convention and
 * serves it at /favicon.ico, where it takes precedence over public/. The
 * repo already had one there — the retired crescent mark — so writing only
 * to public/ left the server still handing out the old icon while every
 * other size was new. Nothing in `npm run verify` catches that; it was
 * caught by diffing the served bytes against the file on disk.
 */
written.push(await ico([16, 32, 48], "src/app/favicon.ico"));
written.push(await png(180, {}, "public/apple-touch-icon.png", { flatten: true }));
written.push(await png(192, {}, "public/icons/icon-192.png"));
written.push(await png(512, {}, "public/icons/icon-512.png"));
written.push(await png(192, { dogSpan: DOG_MASKABLE }, "public/icons/maskable-192.png"));
written.push(await png(512, { dogSpan: DOG_MASKABLE }, "public/icons/maskable-512.png"));

// Superseded by icon.svg and the root apple-touch-icon.
for (const dead of [
  "public/icons/mark.svg",
  "public/icons/apple-touch-icon.png",
  "public/favicon.ico", // src/app/favicon.ico is the one that is served
]) {
  if (existsSync(dead)) {
    unlinkSync(dead);
    console.log(`removed ${dead}`);
  }
}

for (const f of written) console.log(`wrote ${f}`);
console.log(
  `\nkeyline ${(KEYLINE * 100).toFixed(1)}% of width -> ` +
    [16, 32, 180, 512].map((S) => `${S}px:${(S * KEYLINE).toFixed(2)}px`).join("  "),
);
